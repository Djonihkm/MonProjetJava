// Écris une méthode nommée carre qui reçoit un entier nombre 
// et renvoie son carré. Par exemple, carre(5) doit renvoyer 25.

public class Methode {
    public static int carre(int nombre) {
        return nombre * nombre;
    }

    public static void main(String[] args) {
        System.out.println(carre(5));
    }
}